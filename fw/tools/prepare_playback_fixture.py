"""Generate/check the Task 162 fixture using only Python's standard library."""

import argparse
import hashlib
import json
from pathlib import Path
import struct
import wave


ROOT = Path(__file__).resolve().parents[1] / "test" / "test_162_audio_playback"


def read_clip(path):
    with wave.open(str(path), "rb") as recording:
        if (recording.getnchannels(), recording.getsampwidth(), recording.getframerate(),
                recording.getcomptype()) != (1, 2, 8000, "NONE"):
            raise ValueError(f"Unexpected source format: {path.name}")
        raw = recording.readframes(recording.getnframes())
    samples = list(struct.unpack(f"<{len(raw) // 2}h", raw))
    if not samples or max(samples) == min(samples):
        raise ValueError(f"Empty or constant source: {path.name}")
    mean = sum(samples) // len(samples)
    centered = [sample - mean for sample in samples]
    peak = max(abs(sample) for sample in centered)
    scaled = [sample * 4096 // peak for sample in centered]
    # Exact 2x linear interpolation; source bandwidth remains limited to 4 kHz.
    result = []
    for index, sample in enumerate(scaled):
        following = scaled[min(index + 1, len(scaled) - 1)]
        result.extend((sample, (sample + following) // 2))
    return result


def render():
    manifest = json.loads((ROOT / "sources" / "manifest.json").read_text(encoding="utf-8"))
    pcm = [0] * 4000
    for source in manifest["recordings"]:
        path = ROOT / "sources" / source["file"]
        if hashlib.sha256(path.read_bytes()).hexdigest() != source["sha256"]:
            raise ValueError(f"Source checksum mismatch: {path.name}")
        pcm.extend(read_clip(path))
        pcm.extend([0] * 4000)
    if not 16000 <= len(pcm) <= 80000 or max(map(abs, pcm)) > 4096:
        raise ValueError("Fixture duration/peak outside its documented limits")
    pcm_hash = hashlib.sha256(struct.pack(f"<{len(pcm)}h", *pcm)).hexdigest()
    if len(pcm) != manifest["fixture"]["sample_count"] or pcm_hash != manifest["fixture"]["pcm16le_sha256"]:
        raise ValueError("Converted PCM differs from the hardware-tested fixture")
    header = '''#pragma once

#include <stdint.h>

/* Derived FSDD speech, CC BY-SA 4.0. See README.md and sources/manifest.json. */
enum
{
    SPEECH_FIXTURE_RATE_HZ = 16000,
    SPEECH_FIXTURE_SAMPLES = %d
};

extern const int16_t speech_fixture_samples[SPEECH_FIXTURE_SAMPLES];
void speech_fixture_log_info(void);
''' % len(pcm)
    rows = ["    " + ", ".join(str(x) for x in pcm[i:i + 12]) + "," for i in range(0, len(pcm), 12)]
    source = '''/* Generated by tools/prepare_playback_fixture.py. CC BY-SA 4.0; see README.md. */
#include "speech_fixture.h"

#include "esp_log.h"

static const char *TAG = "SPEECH_FIXTURE";

const int16_t speech_fixture_samples[SPEECH_FIXTURE_SAMPLES] =
{
''' + "\n".join(rows) + '''
};

void speech_fixture_log_info(void)
{
    ESP_LOGI(TAG, "Expected speech: one, two, three; 16 kHz PCM16 mono; peak <= 4096");
}
'''
    return {"speech_fixture.h": header, "speech_fixture.c": source}, pcm


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate sources and converted PCM without writing files")
    parser.add_argument("--output-dir", type=Path,
                        default=ROOT.parents[1] / ".pio" / "generated" / "speech_fixture")
    args = parser.parse_args()
    files, pcm = render()
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            path = args.output_dir / name
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"PASS: fixture {len(pcm)} samples, {len(pcm) / 16000:.3f} s, peak {max(map(abs, pcm))}")


if __name__ == "__main__":
    main()
